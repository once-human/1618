// Turns the world's land into a dot grid for the visitors map:
//   node scripts/make-land.mjs > src/content/land.ts
//   node scripts/make-land.mjs 0.5 > src/content/land-fine.ts   (the close-up layer: slow, a couple of minutes)
// One row per 2° of latitude (74°N to 56°S), one bit per 2° of longitude.
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(world, world.objects.land);

const STEP = Number(process.argv[2] ?? 2), TOP = 74, BOTTOM = -56;
const rows = [];
for (let lat = TOP; lat >= BOTTOM; lat -= STEP) {
  const bits = [];
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) bits.push(geoContains(land, [lon, lat]) ? 1 : 0);
  // pack 6 bits per character, base64url alphabet
  const A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
  let s = "";
  for (let i = 0; i < bits.length; i += 6) s += A[parseInt(bits.slice(i, i + 6).join("").padEnd(6, "0"), 2)];
  rows.push(s);
}
const dots = rows.join("").split("").length;
process.stdout.write(`// Generated by scripts/make-land.mjs from Natural Earth (110m, public domain) via world-atlas.
export const ${STEP < 2 ? "LAND_FINE" : "LAND"} = { step: ${STEP}, top: ${TOP}, bottom: ${BOTTOM}, rows: ${JSON.stringify(rows)} };
`);
console.error(`rows ${rows.length}, chars ${dots}`);
